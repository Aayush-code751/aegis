"""Turn result JSON into the LaTeX fragments and figure data the paper uses.

Writes into ``results/paper_assets/``:

    table_main.tex            the main results table body
    table_ablation.tex        the leave-one-out ablation body
    fig_shift_radius.dat      pgfplots coordinates for the worst-case curve
    fig_escalation.dat        pgfplots coordinates for the cost frontier
    summary.md               a one-screen readout of everything

Regenerating the paper from a fresh run is therefore a two-step process --
``run_all.py`` then this script -- with no numbers transcribed by hand.
"""
from __future__ import annotations

import argparse
import json
from typing import Any

from _common import RESULTS, banner

OUT = RESULTS / "paper_assets"


def _load(name: str) -> dict[str, Any] | None:
    path = RESULTS / f"{name}.json"
    if not path.exists():
        print(f"[aegis] missing {path.name}; skipping the assets that need it")
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _fmt(value: Any, digits: int = 3) -> str:
    if value is None:
        return "--"
    if isinstance(value, str):
        return value.replace("_", "\\_")
    return f"{value:.{digits}f}".lstrip("0") if 0 <= float(value) < 1 else f"{value:.{digits}f}"


def table_main(data: dict[str, Any]) -> str:
    lines = ["% generated by experiments/make_paper_assets.py -- do not edit"]
    for corpus, block in data["corpora"].items():
        lines.append(f"% ---- {corpus}")
        rows = block["per_seed"][0]["rows"]
        for row in rows:
            alpha = "--" if row["alpha"] is None else _fmt(row["alpha"], 2)
            cells = [
                str(row["system"]).replace("_", "\\_"),
                alpha,
                _fmt(row.get("P")),
                _fmt(row.get("R")),
                _fmt(row.get("F1")),
                _fmt(row.get("miss")),
                str(row.get("certified") or "--"),
            ]
            lines.append(" & ".join(cells) + r" \\")
    return "\n".join(lines) + "\n"


def table_ablation(data: dict[str, Any]) -> str:
    lines = ["% generated by experiments/make_paper_assets.py -- do not edit"]
    for row in data["resplits"][0]["rows"]:
        cells = [
            str(row["variant"]).replace("_", "\\_"),
            _fmt(row.get("F1")),
            _fmt(row.get("delta_F1")),
            _fmt(row.get("miss_at_alpha")),
            _fmt(row.get("rho_star"), 2),
            "yes" if row.get("no_certificate") else "no",
        ]
        lines.append(" & ".join(cells) + r" \\")
    return "\n".join(lines) + "\n"


def fig_shift(data: dict[str, Any]) -> str:
    head = ["# rho  R_rho   (generated; see experiments/exp02_shift_radius.py)"]
    body = [f"{p['rho']:.4f} {p['R_rho']:.6f}" for p in data["worst_case_trace"]]
    tail = [
        f"# rho_star={data['rho_star']}  rho_star_hat={data['rho_star_hat']}",
        *[
            f"# audit {a['corpus']}: rho_hat={a['rho_hat']} verdict={a['verdict_before_labels']}"
            f" realised={a['realised_leakage']} correct={a['verdict_correct']}"
            for a in data["audits"]
        ],
    ]
    return "\n".join(head + body + tail) + "\n"


def fig_escalation(data: dict[str, Any]) -> str:
    out = ["# budget F1 miss   policy=review"]
    for row in data["frontier_review_policy"]:
        out.append(f"{row['budget']:.4f} {row['F1']:.4f} {row['miss']:.4f}")
    out.append("# budget F1 miss   policy=oracle (upper bound, gold-label resolver)")
    for row in data["frontier_oracle_upper_bound"]:
        out.append(f"{row['budget']:.4f} {row['F1']:.4f} {row['miss']:.4f}")
    return "\n".join(out) + "\n"


def summary(blobs: dict[str, dict[str, Any] | None]) -> str:
    md: list[str] = ["# AEGIS run summary", ""]
    exp02 = blobs.get("exp02_shift_radius")
    if exp02:
        md += [
            "## Layer III: the certificate predicting its own scope", "",
            f"- certified radius `rho_star_hat = {exp02['rho_star_hat']}` "
            f"at `alpha = {exp02['alpha']}`",
            f"- feasibility limit: `alpha_min = {exp02.get('alpha_min_feasible')}`", "",
            "| deployment | rho_hat | verdict (pre-label) | realised leakage | verdict correct |",
            "|---|---|---|---|---|",
        ]
        for a in exp02["audits"]:
            md.append(
                f"| {a['corpus']} | {a['rho_hat']} | {a['verdict_before_labels']} "
                f"| {a['realised_leakage']} | {'yes' if a['verdict_correct'] else 'NO'} |"
            )
        md.append("")
    exp04 = blobs.get("exp04_monitor")
    if exp04:
        md += ["## Layer IV: monitor validity", "",
               "| monitor | false-alarm rate at nominal threshold |", "|---|---|"]
        for k, v in exp04["part_a_nominal_false_alarm"].items():
            md.append(f"| {k} | {v} |")
        md += ["", f"nominal level = {exp04['delta']}", ""]
    exp05 = blobs.get("exp05_chao")
    if exp05:
        md += ["## Layer IV: dark-matter bound coverage", "",
               "| corpus | coverage (all types) | coverage (informative types) |",
               "|---|---|---|"]
        for corpus, block in exp05["corpora"].items():
            md.append(f"| {corpus} | {block['coverage']} | "
                      f"{block.get('coverage_informative', '--')} |")
        md.append("")
    exp06 = blobs.get("exp06_escalation")
    if exp06:
        sub = exp06["submodularity"]
        md += ["## Layer V: submodular escalation", "",
               f"- worst greedy/optimum ratio = {sub['worst_ratio']} "
               f"(bound {sub['bound']}): {'PASS' if sub['passes_bound'] else 'FAIL'}", ""]
    return "\n".join(md) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.parse_args()
    banner("paper assets")
    OUT.mkdir(parents=True, exist_ok=True)
    blobs = {
        name: _load(name)
        for name in ("exp01_main_table", "exp02_shift_radius", "exp03_ablation",
                     "exp04_monitor", "exp05_chao", "exp06_escalation")
    }
    written: list[str] = []
    if blobs["exp01_main_table"]:
        (OUT / "table_main.tex").write_text(table_main(blobs["exp01_main_table"]), encoding="utf-8")
        written.append("table_main.tex")
    if blobs["exp03_ablation"]:
        (OUT / "table_ablation.tex").write_text(table_ablation(blobs["exp03_ablation"]), encoding="utf-8")
        written.append("table_ablation.tex")
    if blobs["exp02_shift_radius"]:
        (OUT / "fig_shift_radius.dat").write_text(fig_shift(blobs["exp02_shift_radius"]), encoding="utf-8")
        written.append("fig_shift_radius.dat")
    if blobs["exp06_escalation"]:
        (OUT / "fig_escalation.dat").write_text(fig_escalation(blobs["exp06_escalation"]), encoding="utf-8")
        written.append("fig_escalation.dat")
    (OUT / "summary.md").write_text(summary(blobs), encoding="utf-8")
    written.append("summary.md")
    for name in written:
        print(f"[aegis] wrote results/paper_assets/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
